const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {randomUUID}=require('node:crypto');

test('1.3 group controls, hidden DMs, owner-only moderation and IP retention',async()=>{
 const {PGlite}=require('@electric-sql/pglite');const db=new PGlite();
 try{
  await db.exec(`create role anon;create role authenticated;create role service_role;create schema auth;
  create table auth.users(id uuid primary key,email text,raw_user_meta_data jsonb,created_at timestamptz not null default now());
  create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
  create schema realtime;create table realtime.messages(topic text,extension text,payload jsonb);alter table realtime.messages enable row level security;
  create function realtime.topic() returns text language sql stable as $$select current_setting('request.jwt.claim.topic',true)$$;
  grant usage on schema auth,realtime to authenticated,anon;grant execute on function auth.uid(),realtime.topic() to authenticated,anon;grant select,insert on realtime.messages to authenticated;create publication supabase_realtime;`);
  for(const file of ['setup.sql','upgrade-1.1.sql','upgrade-to-1.2.sql','upgrade-1.3.sql','upgrade-1.3.sql','upgrade-1.3.1.sql','upgrade-1.3.1.sql','upgrade-1.4.0.sql','upgrade-1.4.0.sql'])
   await db.exec(fs.readFileSync(require.resolve('../supabase/'+file),'utf8'));
  const alice=randomUUID(),bob=randomUUID(),eve=randomUUID();
  for(const [id,name] of [[alice,'alice'],[bob,'bob'],[eve,'eve']])
   await db.query('insert into auth.users(id,email,raw_user_meta_data) values($1,$2,$3)',[id,name+'@users.example.com',JSON.stringify({username:name})]);
  const user=async id=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id||'']);await db.exec('set role authenticated');};
  await user(alice);
  const dm=(await db.query("select public.start_dm('bob') id")).rows[0].id;
  const group=(await db.query("select public.create_group('Crew',ARRAY['bob']) id")).rows[0].id;
  await db.query("insert into public.messages(room_id,body) values($1,'shared history')",[dm]);
  await db.query("insert into public.messages(room_id,body) values($1,'group history')",[group]);
  await db.query("select set_config('request.jwt.claim.topic',$1,false)",['pocketchat-typing:'+group]);
  await db.query("insert into realtime.messages(topic,extension,payload) values($1,'broadcast','{}')",['pocketchat-typing:'+group]);
  assert.equal((await db.query('select count(*)::int count from realtime.messages')).rows[0].count,1,'current group members can send typing broadcasts');
  await user(eve);await db.query("select set_config('request.jwt.claim.topic',$1,false)",['pocketchat-typing:'+group]);
  assert.equal((await db.query('select count(*)::int count from realtime.messages')).rows[0].count,0,'nonmembers cannot receive typing broadcasts');
  await assert.rejects(db.query("insert into realtime.messages(topic,extension,payload) values($1,'broadcast','{}')",['pocketchat-typing:'+group]));
  await user(alice);
  await db.query("update public.profiles set about_me='Likes hiking' where id=$1",[alice]);
  assert.equal((await db.query('select about_me from public.profiles where id=$1',[alice])).rows[0].about_me,'Likes hiking');
  assert.equal((await db.query("update public.profiles set about_me='impersonation' where id=$1",[bob])).rowCount,0);
  await db.query("update public.rooms set name='New crew',avatar_data='data:image/jpeg;base64,/9j/AA==' where id=$1",[group]);
  assert.equal((await db.query('select name,avatar_data from public.rooms where id=$1',[group])).rows[0].name,'New crew');
  assert.equal((await db.query("update public.rooms set name='Renamed DM' where id=$1",[dm])).rowCount,0);
  await assert.rejects(db.query("update public.rooms set avatar_data='https://example.test/p.png' where id=$1",[group]));
  await db.query('insert into public.hidden_rooms(user_id,room_id) values($1,$2)',[alice,dm]);
  assert.equal((await db.query('select room_id from public.hidden_rooms')).rows[0].room_id,dm);
  await assert.rejects(db.query('insert into public.hidden_rooms(user_id,room_id) values($1,$2)',[bob,dm]));
  await assert.rejects(db.query('insert into public.hidden_rooms(user_id,room_id) values($1,$2)',[alice,group]));
  await db.query('select public.leave_group($1)',[group]);
  assert.equal((await db.query('select * from public.room_members where room_id=$1 and user_id=$2',[group,alice])).rows.length,0);
  assert.equal((await db.query('select body from public.messages where room_id=$1',[group])).rows.length,0,'a member who left no longer reads group history');
  await assert.rejects(db.query('select public.leave_group($1)',[group]));
  await user(bob);
  const groupNow=(await db.query('select name from public.rooms where id=$1',[group])).rows[0];
  assert.equal(groupNow.name,'New crew');
  await db.query("update public.rooms set name='Anyone can rename' where id=$1",[group]);
  assert.equal((await db.query('select name from public.rooms where id=$1',[group])).rows[0].name,'Anyone can rename');
  assert.equal((await db.query('select body from public.messages where room_id=$1',[group])).rows[0].body,'group history','remaining members keep the shared history');
  assert.equal((await db.query('select body from public.messages where room_id=$1',[dm])).rows[0].body,'shared history');
  assert.equal((await db.query('select * from public.hidden_rooms')).rows.length,0);
  await assert.rejects(db.query('select * from public.moderation_ip_events'));
  await assert.rejects(db.query('select * from private.app_owner'));
  await assert.rejects(db.query('select * from public.moderation_overview()'));
  await db.exec('reset role');
  const f1='a'.repeat(64),f2='b'.repeat(64);
  await db.query('insert into private.app_owner(singleton,user_id) values(true,$1)',[alice]);
  await db.query('insert into public.moderation_ip_events(user_id,ip_address,ip_fingerprint) values($1,$2,$3),($4,$5,$3),($6,$7,$8)',
   [alice,'203.0.113.42',f1,bob,'203.0.113.42',eve,'2001:db8::9',f2]);
  await db.query("update public.moderation_ip_events set seen_at=now()-interval '8 days' where user_id=$1",[eve]);
  await db.query('select private.purge_moderation_ip_events()');
  const ev=(await db.query('select ip_address from public.moderation_ip_events where user_id=$1',[eve])).rows[0];
  assert.equal(ev.ip_address,null,'raw IPs age out after seven days');
  await db.exec('set role service_role');
  assert.equal((await db.query('select public.record_moderation_ip_event($1,$2,$3) recorded',[eve,'2001:db8::9',f2])).rows[0].recorded,true);
  assert.equal((await db.query('select public.record_moderation_ip_event($1,$2,$3) recorded',[eve,'2001:db8::9',f2])).rows[0].recorded,false,'repeat records are throttled');
  await db.exec('reset role');
  await user(alice);
  assert.equal((await db.query('select public.is_app_owner() owner')).rows[0].owner,true);
  const rows=(await db.query('select * from public.moderation_overview()')).rows;
  const aRow=rows.find(row=>row.account_id===alice),bRow=rows.find(row=>row.account_id===bob);
  assert.equal(aRow.last_ip,'203.0.113.42');
  assert.equal(aRow.possible_matches[0].username,'bob');
  assert.equal(bRow.possible_matches[0].username,'alice');
  await assert.rejects(db.query('select public.moderation_delete_account($1)',[alice]));
  await user(bob);
  const bobGroup=(await db.query("select public.create_group('Bob room',ARRAY['alice']) id")).rows[0].id;
  await db.query("insert into public.messages(room_id,body) values($1,'Bob authored this')",[bobGroup]);
  await user(eve);
  await assert.rejects(db.query('select public.moderation_delete_account($1)',[bob]));
  await user(alice);
  await db.query('select public.moderation_delete_account($1)',[bob]);
  await db.exec('reset role');
  assert.equal((await db.query('select id from public.profiles where id=$1',[bob])).rows.length,0,'the account profile is removed');
  assert.equal((await db.query('select count(*)::int count from public.room_members where user_id=$1',[bob])).rows[0].count,0,'group membership is removed');
  assert.equal((await db.query('select sender_id,body from public.messages where body=$1',['Bob authored this'])).rows[0].sender_id,null,'shared message history is retained anonymously');
  assert.equal((await db.query('select created_by from public.rooms where id=$1',[bobGroup])).rows[0].created_by,null,'a room created by a removed account remains available');
  assert.equal((await db.query('select count(*)::int count from public.moderation_ip_events where user_id=$1',[bob])).rows[0].count,0,'account IP records are removed with the account');
  await user(eve);assert.equal((await db.query('select public.is_app_owner() owner')).rows[0].owner,false);
  await assert.rejects(db.query('select * from public.moderation_overview()'));
 }finally{await db.close();}
});
